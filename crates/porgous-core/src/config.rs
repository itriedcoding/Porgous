//! Configuration loading and validation.
//!
//! Resolution order: built-in defaults, TOML file, then `PORGOUS_*` environment
//! variables. Secrets are never written back into the config file.

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

pub const DEFAULT_CONFIG_PATHS: [&str; 3] =
    ["/etc/porgous/porgous.toml", "porgous.toml", "config/porgous.toml"];

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default)]
pub struct Config {
    /// Directory holding volumes, backups, eggs and temporary files.
    pub data_dir: PathBuf,
    /// `sqlite:///path/to/porgous.db` or `postgres://user:pass@host/db`.
    pub database_url: String,
    /// Address the panel listens on.
    pub bind: String,
    /// Externally reachable URL, used for cookies, CORS and links.
    pub public_url: String,
    pub panel_name: String,
    /// Session lifetime in hours.
    pub session_ttl_hours: i64,
    /// Set to true when served over HTTPS (recommended behind a TLS proxy).
    pub secure_cookies: bool,
    /// Reverse proxy addresses whose `X-Forwarded-For` header is trusted.
    pub trusted_proxies: Vec<String>,
    pub allow_registration: bool,
    pub allow_user_servers: bool,
    pub max_upload_bytes: u64,
    /// 32-byte base64 master key. Generated into `<data_dir>/secret.key` if absent.
    pub secret_key: Option<String>,
    pub rate_limit: RateLimitConfig,
    pub docker: DockerConfig,
    pub node: NodeConfig,
    pub updates: UpdateConfig,
    pub tls: TlsConfig,
    pub admin: AdminConfig,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default)]
pub struct RateLimitConfig {
    pub enabled: bool,
    /// General API budget per client IP and minute.
    pub requests_per_minute: u32,
    /// Login/register attempts per client IP and minute.
    pub auth_per_minute: u32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default)]
pub struct DockerConfig {
    /// When false, servers cannot be started on this host and the API says so.
    pub enabled: bool,
    /// e.g. `unix:///var/run/docker.sock` or `tcp://10.0.0.5:2376`.
    pub host: Option<String>,
    /// Bridge network shared by game containers.
    pub network: String,
    /// Default image used by the generic application egg.
    pub default_image: String,
    pub timezone: String,
    /// Additional memory allowed on top of the game limit (MB).
    pub memory_overhead_mb: i64,
    /// Run containers as this uid:gid when the image supports it.
    pub container_user: Option<String>,
    /// Seconds to wait for a graceful stop before killing.
    pub stop_timeout_secs: u64,
    /// How many lines of historical logs to send on console connect.
    pub console_history_lines: u32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default)]
pub struct NodeConfig {
    /// Name used for the automatically registered local node.
    pub name: String,
    /// Agent listen address (standalone agent only).
    pub bind: String,
    /// Data directory of a standalone agent.
    pub data_dir: PathBuf,
    /// Bearer token used by the panel. Generated by the panel when adding a node.
    pub token: String,
    /// HMAC secret for signed node requests. Generated by the panel when adding a node.
    pub secret: String,
    pub sftp_port: u16,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default)]
pub struct UpdateConfig {
    pub enabled: bool,
    /// GitHub repository in `owner/name` form.
    pub repo: String,
    /// `stable` or `prerelease`.
    pub channel: String,
    /// Base64 or hex Ed25519 public key used to verify release signatures.
    /// Empty means update installation is refused (checking still works).
    pub public_key: String,
    pub check_interval_hours: u64,
    /// Apply updates automatically after a successful verification.
    pub auto_apply: bool,
    pub asset_prefix: String,
    /// Optional command run after a successful update install (for example
    /// `systemctl restart porgous`). Empty means the operator restarts manually.
    pub restart_command: String,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct TlsConfig {
    pub cert: Option<PathBuf>,
    pub key: Option<PathBuf>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct AdminConfig {
    /// Bootstrap administrator created on first launch when the database is empty.
    pub email: String,
    pub username: String,
    pub password: String,
}

